"""Opt-in, independently checked Lane--Emden reference for 0 <= x <= 1.

Set BFLNN_REFERENCE_ARCHIVE to reference_precision.npz to enable use by
experiment wrappers. Unset it to retain the original DOP853 functions.
The archive is generated by ../reference_precision.py: 40/60 decimal
precision, degree 160/240 origin-series convergence and ODE residual checks.
Exact matching of the archived 500- and 11-point grids avoids interpolation;
other points use the archived 60-digit coefficients with 60-digit Horner
evaluation. Only the returned arrays are rounded to float64.

This helper never silently substitutes a lower-precision solver if the
archive is missing or invalid. source_metadata() identifies the actual data
source for raw experiment records. Reference changes affect error evaluation,
not the ODE training objective or the optimizer.
"""
from __future__ import annotations

from functools import lru_cache
import hashlib
import json
import os
from pathlib import Path

import mpmath as mp
import numpy as np


ENVIRONMENT_VARIABLE = "BFLNN_REFERENCE_ARCHIVE"
PREFIXES = {0.5: "n05", 1.5: "n15", 2.0: "n2", 3.0: "n3", 4.0: "n4"}


def enabled():
    return bool(os.environ.get(ENVIRONMENT_VARIABLE, "").strip())


def archive_path():
    value = os.environ.get(ENVIRONMENT_VARIABLE, "").strip()
    if not value:
        raise RuntimeError(f"Set {ENVIRONMENT_VARIABLE} to the checked reference_precision.npz file")
    path = Path(value).expanduser().resolve()
    if not path.is_file():
        raise FileNotFoundError(f"Verified reference archive does not exist: {path}")
    return path


@lru_cache(maxsize=2)
def _load_archive(path):
    with np.load(path, allow_pickle=False) as archive:
        data = {key: archive[key].copy() for key in archive.files}
    for grid in ("x", "x11"):
        if grid not in data or data[grid].ndim != 1 or not np.all(np.isfinite(data[grid])):
            raise ValueError(f"Invalid/missing {grid} grid in verified reference archive {path}")
    report_path = Path(path).with_suffix(".json")
    if not report_path.is_file():
        raise FileNotFoundError(f"Verified reference convergence report missing: {report_path}")
    report = json.loads(report_path.read_text(encoding="utf-8"))
    if not report.get("all_convergence_checks_pass", False):
        raise ValueError(f"Reference convergence checks did not pass: {report_path}")
    return data


@lru_cache(maxsize=2)
def _metadata(path):
    _load_archive(path)
    return {"method": "independent_origin_power_series_60dps_order240",
            "archive": path, "archive_sha256": hashlib.sha256(Path(path).read_bytes()).hexdigest(),
            "exact_grid_lookup": ["500point", "11point"],
            "other_points": "60dps_Horner_from_checked_coefficients; no interpolation",
            "supported_interval": [0.0, 1.0], "returned_dtype": "float64"}


def source_metadata():
    if not enabled():
        return {"method": "original_paper_reference", "verified_reference_enabled": False}
    return {"verified_reference_enabled": True, **_metadata(str(archive_path()))}


def _coefficients(n, terms=120):
    """Fallback for analytic indices; nonexact indices use archived coefficients."""
    nn = mp.mpf(n)
    a, b = [mp.mpf(1)], [mp.mpf(1)]
    for k in range(terms):
        a.append(-b[k]/(2*(k+1)*(2*k+3)))
        ell = k+1
        b.append(mp.fsum(((nn+1)*j-ell)*a[j]*b[ell-j]
                         for j in range(1, ell+1))/ell)
    return a


@lru_cache(maxsize=128)
def _series_values(path, n, points):
    data = _load_archive(path)
    with mp.workdps(60):
        prefix = PREFIXES.get(n)
        if prefix is None:
            if n not in (0.0, 1.0, 5.0):
                raise ValueError(f"Unsupported Lane--Emden index: {n}")
            coeff = _coefficients(n)
        else:
            name = prefix+"_coeff_decimal60"
            if name not in data:
                raise ValueError(f"Missing checked coefficient array {name}; regenerate reference_precision.npz")
            coeff = [mp.mpf(v) for v in data[name]]
        a = list(reversed(coeff))
        da = [2*k*coeff[k] for k in range(len(coeff)-1, 0, -1)]
        d2a = [2*k*(2*k-1)*coeff[k] for k in range(len(coeff)-1, 0, -1)]
        result = []
        for xx in points:
            value = mp.mpf(xx); z = value*value
            result.append((float(mp.polyval(a, z)),
                           float(value*mp.polyval(da, z)),
                           float(mp.polyval(d2a, z))))
    return np.array(result, dtype=float).T


def reference_values(n, x, derivatives=False):
    """Return y, or (y,y',y''), preserving scalar/array shape of x.

    Call only after enabled() in an optional wrapper. Invalid/missing archives
    raise explicitly; no interpolation or silent original-solver fallback.
    """
    path = str(archive_path())
    xx = np.asarray(x, dtype=float)
    if not np.all(np.isfinite(xx)) or np.any(xx < 0) or np.any(xx > 1):
        raise ValueError("Verified origin reference is available only for finite x in [0,1]")
    shape = xx.shape
    flat = xx.reshape(-1)
    if flat.size == 0:
        empty = np.empty(shape, dtype=float)
        return (empty.copy(), empty.copy(), empty.copy()) if derivatives else empty
    data = _load_archive(path)
    prefix = PREFIXES.get(float(n))
    result = None
    if prefix is not None:
        for grid, suffix in (("x", ""), ("x11", "11")):
            if np.array_equal(flat, data[grid]):
                result = np.vstack([data[prefix+"_"+field+suffix] for field in ("y", "dy", "d2y")])
                break
    if result is None:
        result = _series_values(path, float(n), tuple(float(v) for v in flat)).copy()
    values = tuple(float(row[0]) if not shape else row.reshape(shape).copy() for row in result)
    return values if derivatives else values[0]


def smoke_test():
    """Meaningful checks of exact grid lookup, arbitrary points and derivatives."""
    path = str(archive_path()); data = _load_archive(path)
    checks = []
    for n, prefix in PREFIXES.items():
        for grid, suffix in (("x", ""), ("x11", "11")):
            values = reference_values(n, data[grid], derivatives=True)
            if not all(np.array_equal(actual, data[prefix+"_"+field+suffix])
                       for actual, field in zip(values, ("y", "dy", "d2y"))):
                raise AssertionError(f"Exact archive lookup mismatch: n={n}, grid={grid}")
        # Force a nonarchived grid and verify the ODE using independent series derivatives.
        points = np.array([.000123, .137, .537, .937, 1.])
        y, dy, d2y = reference_values(n, points, derivatives=True)
        residual = d2y+2*dy/points+y**n
        if np.max(np.abs(residual)) > 5e-15:
            raise AssertionError(f"Arbitrary-grid ODE residual too large: n={n}")
        if not isinstance(reference_values(n, .137), float):
            raise AssertionError("Scalar shape was not preserved")
        checks.append({"n": n, "max_float64_ode_residual": float(np.max(np.abs(residual)))})
    with mp.workdps(60):
        for n in (0., 1., 5.):
            points = np.array([0., .00123, .123, .567, 1.])
            expected = []
            for v in points:
                t = mp.mpf(float(v))
                exact = 1-t*t/6 if n == 0 else (mp.sin(t)/t if t else mp.mpf(1)) if n == 1 else (1+t*t/3)**(-mp.mpf('.5'))
                expected.append(float(exact))
            if not np.array_equal(reference_values(n, points), expected):
                raise AssertionError(f"Series sanity check against exact n={n} failed")
    return {"all_smoke_checks_pass": True, "checks": checks, "source": source_metadata()}


if __name__ == "__main__":
    smoke = smoke_test()
    (Path(__file__).resolve().parent.parent / 'verified_reference_smoke.json').write_text(
        json.dumps(smoke, indent=2)+'\n', encoding='utf-8')
    print(json.dumps(smoke, indent=2))
